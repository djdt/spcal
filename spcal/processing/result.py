import typing
from pathlib import Path

import numpy as np

from spcal import particle
from spcal.detection import background_mask, detection_maxima
from spcal.isotope import SPCalIsotopeBase
from spcal.limit import SPCalLimit

if typing.TYPE_CHECKING:
    from spcal.processing.method import SPCalProcessingMethod


class SPCalProcessingResult:
    """A container for results processed by an `SPCalProcessingMethod`.

    Attributes:
        background: mean value of all non-detection and unmasked data
        background_std: std for `background`
        peak_indicies: index for each detection shared across all results,
            generated by `SPCalProcessingMethod.assignPeakIndicies`
        number_peak_indicies: total number of detections across all results,
            may not equal `number`, generated by `SPCalProcessingMethod.assignPeakIndicies`
        filter_indicies: indicies for unfiltered detections,
            generated by `SPCalProcessingMethod.filterResults`
    """

    def __init__(
        self,
        isotope: SPCalIsotopeBase,
        limit: SPCalLimit,
        method: "SPCalProcessingMethod",
        event_time: float,
        data_file_path: Path,
        signals: np.ndarray,
        mask: np.ndarray,
        times: np.ndarray,
        detections: np.ndarray,
        regions: np.ndarray,
        indicies: np.ndarray | None = None,
    ):
        """
        Args:
            isotope: the isotope for the result
            limit: limit used to calculate result
            method: reference to the method used
            event_time: time in seconds for a single event (dwell time)
            data_file_path: path to original file
            signals: data in counts
            mask: boolean mask of valid regions
            times: array of event times in seconds
            detections: array of dectection sums
            regions: array of dectection start, ends indicies, shape (N, 2)
            indicies: optional peak_indicies
        """

        self.isotope = isotope
        self.limit = limit

        self.data_file_path = data_file_path
        self.method = method

        self.event_time = event_time

        self.signals = signals
        self.mask = mask
        self.times = times

        self.detections = detections
        self.maxima = detection_maxima(signals, regions)
        self.regions = regions

        self.peak_indicies = indicies
        self.number_peak_indicies = 0
        self.filter_indicies = np.arange(detections.size)

        bg_mask = background_mask(regions, signals.size)
        bg_mask = np.logical_and(bg_mask, self.mask)

        self.background = float(np.mean(signals[bg_mask]))
        self.background_error = float(np.std(signals[bg_mask], mean=self.background))

    def __repr__(self) -> str:  # pragma: no cover
        return f"SPCalProcessingResult(number={self.number})"

    @property
    def num_events(self) -> int:
        return int(np.count_nonzero(np.isfinite(self.signals[self.mask])))

    @property
    def total_time(self) -> float:
        return self.event_time * self.num_events

    @property
    def valid_events(self) -> int:
        """Number of valid (non nan) events."""
        return int(np.count_nonzero(~np.isnan(self.signals[self.mask])))

    @property
    def ionic_background(self) -> float | None:
        """Background in kg/L.

        Requires 'response' input.
        """
        if self.isotope not in self.method.isotope_options:
            return None
        response = self.method.isotope_options[self.isotope].response
        if response is None:  # pragma: no cover
            return None
        return float(self.background / response)

    @property
    def number(self) -> int:
        """Number of non-zero detections."""
        return self.filter_indicies.size

    @property
    def number_error(self) -> int:
        """Sqrt of ``number``."""
        return np.sqrt(self.number)

    @property
    def number_concentration(self) -> float | None:
        if (
            self.method.instrument_options.efficiency is None
            or not self.method.instrument_options.efficiency > 0.0
            or self.method.instrument_options.uptake is None
            or not self.method.instrument_options.uptake > 0.0
        ):  # pragma: no cover
            return None

        return np.around(
            particle.particle_number_concentration(
                self.number,
                self.method.instrument_options.efficiency,
                self.method.instrument_options.uptake,
                self.total_time,
            )
        )

    @property
    def mass_concentration(self) -> float | None:
        if (
            not self.canCalibrate("mass")
            or self.method.instrument_options.efficiency is None
            or self.method.instrument_options.uptake is None
        ):  # pragma: no cover
            return None
        masses = self.calibrated("mass")

        return particle.particle_total_concentration(
            masses,
            self.method.instrument_options.efficiency,
            self.method.instrument_options.uptake,
            self.total_time,
        )

    def peakValues(self) -> np.ndarray:
        if self.peak_indicies is None:  # pragma: no cover
            raise ValueError("peak_indicies not generated")
        values = np.zeros(self.number_peak_indicies, dtype=self.detections.dtype)
        np.add.at(
            values,
            self.peak_indicies[self.filter_indicies],
            self.detections[self.filter_indicies],
        )
        return values

    def canCalibrate(self, key: str) -> bool:  # pragma: no cover, tested in method
        return self.method.canCalibrate(key, self.isotope)

    def calibrated(self, key: str, filtered: bool = True) -> np.ndarray:
        values = self.detections
        if filtered:
            values = values[self.filter_indicies]
        result = self.method.calibrateTo(values, key, self.isotope, self.event_time)
        return np.asanyarray(result)

    def calibrateTo(
        self, value: float | np.ndarray, key: str
    ) -> float | np.ndarray:  # pragma: no cover, tested in method
        return self.method.calibrateTo(value, key, self.isotope, self.event_time)
